"""Where scan images live: a local folder in development, a private Supabase Storage
bucket in production. Keys are always generated by the app (never from a filename the
user sent), e.g. ``uploads/<random>/original.jpg`` or ``scans/<id>/crop_12.png``."""

from __future__ import annotations

import re
from pathlib import Path
from typing import Protocol

import httpx

from app.config import Settings

_KEY = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_./-]{0,250}$")


class StorageError(RuntimeError):
    pass


def check_key(key: str) -> str:
    """Reject anything that could escape the storage root."""
    if not _KEY.match(key) or ".." in key.split("/") or "//" in key:
        raise StorageError(f"invalid storage key {key!r}")
    return key


class Storage(Protocol):
    def put(self, key: str, data: bytes, content_type: str) -> None: ...

    def get(self, key: str) -> bytes: ...

    def delete(self, keys: list[str]) -> None:
        """Remove these files; missing ones are fine."""
        ...

    def url(self, key: str) -> str:
        """A URL the logged-in app can load the file from."""
        ...


class LocalStorage:
    """Files under ``root``; served to logged-in users by ``GET /api/files/{key}``."""

    def __init__(self, root: str | Path) -> None:
        self.root = Path(root).resolve()

    def _path(self, key: str) -> Path:
        path = (self.root / check_key(key)).resolve()
        if self.root not in path.parents:
            raise StorageError(f"invalid storage key {key!r}")
        return path

    def put(self, key: str, data: bytes, content_type: str) -> None:
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_suffix(path.suffix + ".part")
        tmp.write_bytes(data)
        tmp.replace(path)

    def get(self, key: str) -> bytes:
        path = self._path(key)
        if not path.is_file():
            raise StorageError(f"no stored file {key!r}")
        return path.read_bytes()

    def delete(self, keys: list[str]) -> None:
        for key in keys:
            path = self._path(key)
            path.unlink(missing_ok=True)
            for parent in path.parents:  # tidy empty folders up to the root
                if parent == self.root:
                    break
                if not parent.exists():
                    continue
                if any(parent.iterdir()):
                    break
                parent.rmdir()

    def url(self, key: str) -> str:
        return f"/api/files/{check_key(key)}"


class SupabaseStorage:
    """Private bucket via the Storage REST API with the service-role key (server only).
    Viewers get short-lived signed URLs, so the bucket never needs to be public."""

    def __init__(
        self,
        base_url: str,
        service_key: str,
        bucket: str,
        signed_seconds: int,
        client: httpx.Client | None = None,
    ) -> None:
        self.base = base_url.rstrip("/") + "/storage/v1"
        self.bucket = bucket
        self.signed_seconds = signed_seconds
        self.client = client or httpx.Client(timeout=30)
        self.headers = {"Authorization": f"Bearer {service_key}", "apikey": service_key}

    def _check(self, response: httpx.Response, what: str) -> httpx.Response:
        if response.status_code >= 400:
            raise StorageError(f"Supabase Storage {what} failed ({response.status_code})")
        return response

    def put(self, key: str, data: bytes, content_type: str) -> None:
        r = self.client.post(
            f"{self.base}/object/{self.bucket}/{check_key(key)}",
            content=data,
            headers={**self.headers, "Content-Type": content_type, "x-upsert": "true"},
        )
        self._check(r, "upload")

    def get(self, key: str) -> bytes:
        r = self.client.get(
            f"{self.base}/object/{self.bucket}/{check_key(key)}", headers=self.headers
        )
        return self._check(r, "download").content

    def delete(self, keys: list[str]) -> None:
        if not keys:
            return
        r = self.client.request(
            "DELETE",
            f"{self.base}/object/{self.bucket}",
            json={"prefixes": [check_key(k) for k in keys]},
            headers=self.headers,
        )
        self._check(r, "delete")

    def url(self, key: str) -> str:
        r = self.client.post(
            f"{self.base}/object/sign/{self.bucket}/{check_key(key)}",
            json={"expiresIn": self.signed_seconds},
            headers=self.headers,
        )
        signed = self._check(r, "signing").json().get("signedURL")
        if not signed:
            raise StorageError("Supabase Storage returned no signed URL")
        return f"{self.base}{signed}" if signed.startswith("/") else f"{self.base}/{signed}"


def make_storage(settings: Settings) -> Storage:
    if settings.storage_backend == "supabase":
        if not (settings.supabase_url and settings.supabase_service_role_key):
            raise StorageError("SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY must be set")
        return SupabaseStorage(
            settings.supabase_url,
            settings.supabase_service_role_key,
            settings.supabase_bucket,
            settings.signed_url_seconds,
        )
    return LocalStorage(settings.upload_dir)
